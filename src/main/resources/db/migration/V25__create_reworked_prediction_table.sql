CREATE TABLE public.prediction_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    prediction_type_uid UUID NOT NULL,
    prediction_type TEXT NOT NULL,
    description TEXT NOT NULL,
    prediction_selection_type TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT pk_prediction_type_id PRIMARY KEY (id),
    CONSTRAINT uk_prediction_prediction_type_uid UNIQUE (prediction_type_uid),
    CONSTRAINT uk_prediction_prediction_type UNIQUE (prediction_type)
);

CREATE TABLE public.prediction (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  prediction_uid UUID NOT NULL,
  prediction_type_id BIGINT NOT NULL,
  user_team_id BIGINT NOT NULL,
  race_weekend_id BIGINT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,

  CONSTRAINT pk_prediction_id PRIMARY KEY (id),
  CONSTRAINT uk_prediction_prediction_uid UNIQUE (prediction_uid),
  CONSTRAINT uk_prediction_unique_user_team_prediction_type_per_race_weekend UNIQUE (user_team_id, prediction_type_id, race_weekend_id),

  CONSTRAINT fk_prediction_prediction_type_id FOREIGN KEY(prediction_type_id) REFERENCES prediction_type(id),
  CONSTRAINT fk_prediction_user_team_id FOREIGN KEY(user_team_id) REFERENCES user_team(id),
  CONSTRAINT fk_prediction_race_weekend_id FOREIGN KEY(race_weekend_id) REFERENCES race_weekend(id)

);

CREATE TABLE public.prediction_choice (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  prediction_choice_uid UUID NOT NULL,
  prediction_id BIGINT NOT NULL,
  constructor_id BIGINT NULL,
  driver_id BIGINT NOT NULL,
  is_ranked BOOLEAN NOT NULL,
  rank int,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,

  CONSTRAINT pk_prediction_choice_id PRIMARY KEY (id),
  CONSTRAINT uk_prediction_choice_prediction_choice_uid UNIQUE (prediction_choice_uid),

  CONSTRAINT fk_prediction_choice_prediction_id FOREIGN KEY(prediction_id) REFERENCES prediction(id),
  CONSTRAINT fk_prediction_constructor_id FOREIGN KEY(constructor_id) REFERENCES constructor(id),
  CONSTRAINT fk_prediction_driver_id FOREIGN KEY(driver_id) REFERENCES driver(id),

  CHECK ((driver_id IS NOT NULL) OR (constructor_id IS NOT NULL)),
  CHECK (NOT (driver_id IS NOT NULL AND constructor_id IS NOT NULL)),
  CHECK (NOT (is_ranked = TRUE AND rank IS NULL))

);

CREATE UNIQUE INDEX ux_prediction_choice_prediction_rank_not_null
    ON prediction_choice (prediction_id, rank)
    WHERE rank IS NOT NULL;